// Looks up a country name from an arbitrary runtime string (e.g. URL param, localStorage value).
// Returns undefined if the code is not recognised.
export const getCountryName = (code: string): string | undefined => {
  const upper = code.toUpperCase();
  return isCountryCode(upper) ? countryNames[upper] : undefined;
};

export const sortRegions = (regions: readonly CountryCode[]): CountryCode[] => {
  return [...regions].sort((a, b) => countryNames[a].localeCompare(countryNames[b]));
};
